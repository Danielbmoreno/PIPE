-- Los helpers privados consultan exclusivamente la identidad verificada del solicitante.
-- La compatibilidad por email solo se permite mientras el perfil no tenga auth_user_id.
create or replace function private.pipe_identity()
returns table(usuario_id integer, rol_id integer)
language sql stable security definer set search_path = '' as $$
  select u.id, u.rol_id from public.usuarios u
  where (select auth.uid()) is not null and u.activo is true
    and (u.auth_user_id = (select auth.uid()) or
         (u.auth_user_id is null and lower(u.correo) = lower(auth.jwt()->>'email')))
$$;
create or replace function private.pipe_user_id() returns integer
language sql stable security definer set search_path = '' as $$
  select i.usuario_id from private.pipe_identity() i
$$;
create or replace function private.pipe_role() returns integer
language sql stable security definer set search_path = '' as $$
  select i.rol_id from private.pipe_identity() i
$$;
create or replace function private.pipe_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select i.rol_id = 1 from private.pipe_identity() i), false)
$$;
create or replace function private.pipe_student_access(target integer, staff_only boolean default false)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from private.pipe_identity() i join public.estudiantes e on e.id = target
    where i.rol_id = 1
       or (i.rol_id = 2 and exists(select 1 from public.consejero_estudiantes a where a.estudiante_id = e.id and a.consejero_id = i.usuario_id and a.activo))
       or (not staff_only and i.rol_id = 3 and e.usuario_id = i.usuario_id)
  )
$$;
create or replace function private.pipe_case_access(target integer)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.casos c where c.id = target and private.pipe_student_access(c.estudiante_id,true))
$$;
revoke all on function private.pipe_identity(), private.pipe_user_id(), private.pipe_role(), private.pipe_admin(), private.pipe_student_access(integer,boolean), private.pipe_case_access(integer) from public, anon;
