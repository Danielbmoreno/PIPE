create or replace function public.pipe_access_context() returns jsonb
language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object('version',1,'usuario_id',i.usuario_id,'rol_id',i.rol_id,
    'estudiante_ids',coalesce((select jsonb_agg(e.id) from public.estudiantes e),'[]'::jsonb),
    'caso_ids',coalesce((select jsonb_agg(c.id) from public.casos c),'[]'::jsonb),
    'consejeros',coalesce((select jsonb_agg(jsonb_build_object('id',u.id,'nombre',u.nombre,'correo',u.correo)) from public.usuarios u where u.rol_id=2 and u.activo),'[]'::jsonb))
  from private.pipe_identity() i
$$;
revoke all on function public.pipe_access_context() from public,anon;
