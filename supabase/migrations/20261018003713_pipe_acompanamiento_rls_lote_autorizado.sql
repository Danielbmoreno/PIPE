create or replace function private.pipe_validate_record() returns trigger
language plpgsql set search_path = '' as $$
declare parent_student integer; payload jsonb := to_jsonb(new); old_payload jsonb; counselor integer; begin
  if tg_op='UPDATE' then
    old_payload := to_jsonb(old);
    if payload->>'usuario_id' is distinct from old_payload->>'usuario_id' then raise exception 'La autoría original no se puede cambiar'; end if;
    if payload->>'estudiante_id' is distinct from old_payload->>'estudiante_id' then raise exception 'Un registro debe conservar su estudiante original'; end if;
    if tg_table_name='intervenciones' and payload->>'caso_id' is distinct from old_payload->>'caso_id' then raise exception 'Una intervención debe conservar su caso original'; end if;
  end if;
  if payload->>'alerta_id' is not null then
    select estudiante_id into parent_student from public.alertas where id=(payload->>'alerta_id')::integer;
    if parent_student is distinct from (payload->>'estudiante_id')::integer then raise exception 'Alerta de otro estudiante o no autorizada'; end if;
  end if;
  if payload->>'caso_id' is not null and tg_table_name <> 'intervenciones' then
    select estudiante_id into parent_student from public.casos where id=(payload->>'caso_id')::integer;
    if parent_student is distinct from (payload->>'estudiante_id')::integer then raise exception 'Caso de otro estudiante o no autorizado'; end if;
  end if;
  if payload->>'cita_id' is not null then
    select estudiante_id into parent_student from public.citas where id=(payload->>'cita_id')::integer;
    if parent_student is distinct from (payload->>'estudiante_id')::integer then raise exception 'Cita de otro estudiante o no autorizada'; end if;
    if payload->>'caso_id' is not null and exists(select 1 from public.citas where id=(payload->>'cita_id')::integer and caso_id is not null and caso_id<>(payload->>'caso_id')::integer) then raise exception 'La cita corresponde a otro caso'; end if;
  end if;
  if tg_table_name='consultas' and (payload->>'fecha')::date > (now() at time zone 'America/Bogota')::date then raise exception 'No registrar consultas futuras como realizadas'; end if;
  if tg_table_name='seguimientos' and payload->>'estado'='completado' and (payload->>'fecha')::date > (now() at time zone 'America/Bogota')::date then raise exception 'No completar seguimientos futuros'; end if;
  if tg_table_name='citas' then
    if tg_op='INSERT' and (new.fecha is null or new.hora is null or new.consejero_id is null or coalesce(trim(new.motivo),'')='') then raise exception 'La cita requiere fecha, hora, consejero y motivo'; end if;
    if new.estado is null or new.estado not in ('programada','atendida','cancelada','no asistió') then raise exception 'Estado de cita no válido'; end if;
    if new.estado in ('atendida','no asistió') and ((new.fecha + new.hora) at time zone 'America/Bogota') > now() then raise exception 'No registrar una atención futura como realizada'; end if;
    if new.hora_fin is not null and new.hora_fin <= new.hora then raise exception 'La hora final debe ser posterior a la inicial'; end if;
    if new.consejero_id is not null then
      select rol_id into counselor from public.usuarios where id=new.consejero_id and activo is true;
      if counselor is distinct from 2 or not exists(select 1 from public.consejero_estudiantes a where a.consejero_id=new.consejero_id and a.estudiante_id=new.estudiante_id and a.activo) then raise exception 'Profesional sin asignación activa'; end if;
      perform pg_advisory_xact_lock(new.consejero_id, (new.fecha-date '2000-01-01'));
      if new.estado='programada' and exists(select 1 from public.citas c where c.id<>new.id and c.consejero_id=new.consejero_id and c.fecha=new.fecha and c.estado='programada' and c.hora<coalesce(new.hora_fin,new.hora+interval '1 hour') and coalesce(c.hora_fin,c.hora+interval '1 hour')>new.hora) then raise exception 'El horario se superpone con otra cita'; end if;
    end if;
  end if;
  return new;
end $$;
create or replace function private.pipe_validate_student() returns trigger
language plpgsql set search_path = '' as $$ begin
  if new.semestre is not null and new.semestre not between 1 and 20 then raise exception 'Semestre fuera de rango'; end if;
  if (select private.pipe_role())=2 and (to_jsonb(new)-array['semestre','estado','rendimiento_resumen','estado_acompanamiento']) is distinct from (to_jsonb(old)-array['semestre','estado','rendimiento_resumen','estado_acompanamiento']) then raise exception 'El consejero solo puede editar el seguimiento académico de sus asignados'; end if;
  return new;
end $$;
create or replace function private.pipe_validate_assignment() returns trigger
language plpgsql set search_path = '' as $$ begin
  if not exists(select 1 from public.usuarios where id=new.consejero_id and rol_id=2 and activo is true) then raise exception 'La asignación requiere un consejero activo'; end if;
  return new;
end $$;
